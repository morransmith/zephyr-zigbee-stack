/**
 * Application Device Version of a device type: the highest Rev of its revision history in the
 * DTL, 2 for the Color Dimmable Light and the Extended Color Light and 1 for the other types.
 */
#define ZZB_DEVICE_VERSION(id)                                                                     \
	((id) == ZZB_DEVICE_COLOR_DIMMABLE_LIGHT || (id) == ZZB_DEVICE_EXTENDED_COLOR_LIGHT ? 2 : 1)

